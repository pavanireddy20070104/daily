//Print 1 to 5
public class Hello{
  public static void main(String[]args){
  for(int i=1;i <= 5; i++){
    System.out.println(i);
    }
  }
}

//print 5 to 0 (reverse order)
public class Hello{
  public static void main(String[]args){
  for(int i=5;i >0; i--){
    System.out.println(i);
   }
  }
}


